	static std::unordered_map<std::string, const char*> gMap;
	static std::once_flag gOnce;

	static void Build() {
		gMap.reserve(std::size(kEntries));
		for (const auto& [en, ja] : kEntries) {
			gMap.emplace(en, ja);
		}
	}

	const char* Get(const char* text) {
		if (text == nullptr) return text;
		if (State.Language != 1) return text;
		std::call_once(gOnce, Build);
		auto it = gMap.find(text);
		return it != gMap.end() ? it->second : text;
	}

	const char* Get(const std::string& text) {
		return Get(text.c_str());
	}

	void Reload() {
		if (State.Language == 1) std::call_once(gOnce, Build);
	}
